/** Insere a EAP padrão numa obra que ainda não tem linhas na planilha. Devolve a quantidade de linhas criadas. */
export async function aplicarEapPadrao(c: Cliente, obraId: string): Promise<number> {
  const ids = new Map<string, string>();
  for (const [codigo, nivel, descricao] of EAP_PADRAO) {
    const pai = codigo.includes('.') ? codigo.slice(0, codigo.lastIndexOf('.')) : null;
    const paiId = pai ? (ids.get(pai) ?? null) : null;
    const no = (
      await c.query('INSERT INTO eap_nos (obra_id, pai_id, nivel, codigo, descricao) VALUES ($1,$2,$3,$4,$5) RETURNING id', [obraId, paiId, nivel, codigo, descricao])
    ).rows[0];
    ids.set(codigo, no.id as string);
  }
  return EAP_PADRAO.length;
}
